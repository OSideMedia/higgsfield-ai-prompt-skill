#!/usr/bin/env python3
"""
build_index.py
==============
Generate INDEX.md from every SKILL.md's headings, keep a CONTENTS block at the
top of every long reference file, and verify the QUICK FACTS contract.
Stdlib only.

Why: HARD RULES demand full reads of routed sub-skills, but the largest ones
run 1,000+ lines and partial reads happen in practice. Two mitigations:
  * INDEX.md — a generated heading index so grep-routing lands on anchors
    instead of archaeology.
  * QUICK FACTS — a 15-25 line block at the top of each large sub-skill with
    the enums/caps/gotchas an agent most needs, every line anchor-linked into
    the full section so the facts can't silently detach from their source.
  * CONTENTS — a generated, anchor-linked heading list right under the title of
    every skill file over CONTENTS_THRESHOLD lines that has no QUICK FACTS
    block (Anthropic's skill guidance: a reference file over 100 lines opens
    with a table of contents, so a partial read still shows its scope).

This script is the single authority for both:
  python3 scripts/build_index.py            # regenerate INDEX.md + CONTENTS blocks (also runs checks)
  python3 scripts/build_index.py --check    # verify only; write nothing (CI / validate.py)

Checks enforced (both modes):
  * every sub-skill SKILL.md longer than QUICK_FACTS_THRESHOLD lines (not
    counting its CONTENTS block) has a `## QUICK FACTS` block. The root
    dispatcher is out of scope: HARD RULE 2 makes it a mandatory full read and
    it opens with the HARD RULES checklist, so the partial-read problem QUICK
    FACTS mitigates does not arise there
  * every in-file anchor link inside a QUICK FACTS block resolves to a real
    heading in that file
  * every file contents_files() lists is a no-op for the CONTENTS writer:
    the block is present where it is owed and matches the headings
  * (--check) INDEX.md byte-matches regeneration

Exit codes: 0 ok, 1 check failure.
"""

from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent  # scripts/ → repo root
INDEX = ROOT / "INDEX.md"
QUICK_FACTS_THRESHOLD = 400  # lines; matches the "large sub-skill" cutoff

CONTENTS_THRESHOLD = 100  # lines; Anthropic's "reference files longer than 100 lines"
CONTENTS_BEGIN = "<!-- CONTENTS — generated by scripts/build_index.py; do not hand-edit -->"
CONTENTS_END = "<!-- /CONTENTS -->"
# Root .md files that document the repo, not the skill (validate.py imports this).
REPO_DOCS = {"README.md", "CHANGELOG.md", "CONTRIBUTING.md", "CLAUDE.md"}

HEADING_RE = re.compile(r"^(#{1,6})\s+(.+?)\s*#*\s*$")
INDEX_MAX_LEVEL = 3  # INDEX.md lists h1-h3; anchor validation covers all levels
# A code-fence line: up to three spaces, then three or more backticks or
# tildes, then an info string (CommonMark § Fenced code blocks).
FENCE_RE = re.compile(r"^ {0,3}(`{3,}|~{3,})(.*)$")


def anchor(heading: str) -> str:
    """GitHub's heading slug (github-slugger), exactly:

      1. lowercase;
      2. drop the Unicode categories github-slugger's script/generate-regex.js
         strips — Other_Number, Open/Close/Initial/Final/Other/Dash
         punctuation (except `-`), every Symbol, Control, Private_Use,
         Format, Unassigned, and every Separator except ASCII space — minus
         Alphabetic code points. What survives: letters, marks, Nd/Nl digits,
         connector punctuation (`_`), `-` and ` `. So `—`, `.`, `@`, `(`,
         backticks, `*` emphasis markers and `²` all vanish;
      3. replace EACH space with `-` — no collapsing, no trimming.

    So "Audio — Seedance 2.0" → "audio--seedance-20". The pre-v3.37 version
    collapsed `\\s+` into one hyphen ("audio-seedance-20"): internally
    consistent, so validate certified it, but ~303/932 INDEX anchors and
    103/234 QUICK FACTS links did not resolve on GitHub.
    (ponytail: `str.isalpha()` stands in for the Alphabetic property, so an
    Other_Alphabetic symbol such as a circled letter is dropped where GitHub
    keeps it — none occur in any heading; swap in a real property table if
    one ever does.)"""
    out = []
    for ch in heading.strip().lower():
        cat = unicodedata.category(ch)
        if ch in " -" or cat[0] in "LM" or cat in ("Nd", "Nl", "Pc") or ch.isalpha():
            out.append(ch)
    return "".join(out).replace(" ", "-")


def anchors_for(heads: list[tuple[int, str]]) -> list[str]:
    """Per-file anchor list with GitHub's duplicate-heading suffixes.

    github-slugger's occurrence rule: the first use of a slug is bare; a
    repeat gets `-1`, `-2`, … and every emitted slug is itself reserved, so a
    literal heading "foo-1" after two "foo" headings becomes "foo-1-1".
    Generation and verification both use this, or duplicate headings produce
    links that all land on the first occurrence."""
    occurrences: dict[str, int] = {}
    out = []
    for _, text in heads:
        slug = original = anchor(text)
        while slug in occurrences:
            occurrences[original] += 1
            slug = f"{original}-{occurrences[original]}"
        occurrences[slug] = 0
        out.append(slug)
    return out


def fence_mask(lines: list[str]) -> list[bool]:
    """True for each line that opens, closes or sits inside a code fence. A
    fence closes only on the same character, at least as long as its opener,
    with nothing after it but spaces; an unclosed fence runs to the end. A
    backtick opener whose info string holds a backtick is not a fence.
    (ponytail: fences inside list items and block quotes are not modelled, so
    one indented past three spaces counts as indented code, as it would at the
    top level; swap in a CommonMark parser if a container fence ever holds a
    heading or a CONTENTS marker.)"""
    mask, opener = [], None
    for line in lines:
        m = FENCE_RE.match(line)
        if opener is None:
            opener = m.group(1) if m and not (m.group(1)[0] == "`" and "`" in m.group(2)) else None
            mask.append(opener is not None)
            continue
        mask.append(True)
        if (m and m.group(1)[0] == opener[0] and len(m.group(1)) >= len(opener)
                and not m.group(2).strip()):
            opener = None
    return mask


def heading_lines(lines: list[str]) -> list[tuple[int, int, str]]:
    """(line index, level, text) for every markdown heading outside code fences."""
    out = []
    for i, (line, fenced) in enumerate(zip(lines, fence_mask(lines))):
        if fenced:
            continue
        m = HEADING_RE.match(line)
        if m:
            out.append((i, len(m.group(1)), m.group(2)))
    return out


def headings(text: str) -> list[tuple[int, str]]:
    """(level, text) for every markdown heading outside code fences."""
    return [(level, t) for _, level, t in heading_lines(text.splitlines())]


def skill_files() -> list[Path]:
    """This checkout's SKILL.md files — never those of an agent worktree under
    `.claude/worktrees/` or any nested checkout (scripts/repo_walk.py)."""
    from repo_walk import walk_files
    return walk_files(ROOT, "SKILL.md")


def contents_files() -> list[Path]:
    """Every file a reader of this skill may open: root .md files except the
    repo docs and the generated INDEX.md, and every .md under skills/,
    templates/ and docs/ (minus docs/archive/)."""
    from repo_walk import walk_files
    out = [p for p in sorted(ROOT.glob("*.md"))
           if p.name not in REPO_DOCS and p != INDEX]
    for sub in ("skills", "templates", "docs"):
        out += [p for p in walk_files(ROOT / sub, "*.md", repo_root=ROOT)
                if not (sub == "docs" and p.relative_to(ROOT).parts[1] == "archive")]
    return out


# Heading markup GitHub renders away before it slugs, so a CONTENTS link
# built from the raw text would 404: an inline or reference link, inline
# HTML, a backslash escape, an entity, or `_` / `__` emphasis (an intraword
# `_` is literal). Checked with code spans removed. The writer refuses such
# a heading rather than emit a dead link; none occurs today. A bare bracket
# tag such as `[EMPIRICAL]` renders as itself and slugs the same, so it passes.
# (ponytail: a deny-list of inline syntax; render the heading with a
# CommonMark parser if headings ever need richer markup.)
UNSLUGGABLE_RE = re.compile(r"\]\(|\]\[|<[A-Za-z/!]|\\|&#?\w+;"
                            r"|(?<![A-Za-z0-9])_|_(?![A-Za-z0-9])")


def _link_text(heading: str) -> str:
    return heading.replace("[", "\\[").replace("]", "\\]")


def _frontmatter_end(lines: list[str]) -> int:
    """Index of the first line after a leading `---` frontmatter block (0 if none)."""
    if lines and lines[0] == "---":
        close = next((i for i in range(1, len(lines)) if lines[i] == "---"), None)
        if close is not None:
            return close + 1
    return 0


def _block_span(lines: list[str]) -> tuple[int, int] | None:
    """(begin, end) line indices of the one CONTENTS block outside code fences
    and frontmatter, or None. A begin without an end, a second block, or an
    end without a begin is an error: the writer must never guess which lines
    are its own."""
    spans, begin = [], None
    start = _frontmatter_end(lines)
    for i, fenced in enumerate(fence_mask(lines[start:]), start):
        line = lines[i]
        if fenced:
            continue
        if line == CONTENTS_BEGIN:
            if begin is not None:
                raise ValueError(f"nested {CONTENTS_BEGIN!r}")
            begin = i
        elif line == CONTENTS_END:
            if begin is None:
                raise ValueError(f"{CONTENTS_END!r} with no {CONTENTS_BEGIN!r}")
            spans.append((begin, i))
            begin = None
    if begin is not None:
        raise ValueError(f"{CONTENTS_BEGIN!r} with no {CONTENTS_END!r}")
    if len(spans) > 1:
        raise ValueError(f"{len(spans)} CONTENTS blocks; keep one")
    return spans[0] if spans else None


def _split(text: str) -> tuple[list[str], str]:
    newline = "\r\n" if "\r\n" in text else "\n"
    return text.replace("\r\n", "\n").split("\n"), newline


def _remove_block(lines: list[str]) -> list[str]:
    """`lines` minus the CONTENTS block and the blank line the writer put above it."""
    span = _block_span(lines)
    if span is None:
        return lines
    begin, end = span
    if begin > 0 and lines[begin - 1] == "":
        begin -= 1
    return lines[:begin] + lines[end + 1:]


def without_contents(text: str) -> str:
    """`text` minus its CONTENTS block, if it has one."""
    lines, newline = _split(text)
    return newline.join(_remove_block(lines))


def with_contents(text: str) -> str:
    """`text` with its CONTENTS block inserted, refreshed or moved back into
    place — the fixer whose no-op IS the check. A block already present is
    always kept current; a new one is owed only past CONTENTS_THRESHOLD lines;
    none is kept beside a QUICK FACTS block (which already opens the file with
    anchored facts) or with fewer than two sections to list. The block sits
    right under the title, or under the frontmatter when the file has no
    title in its first 40 lines. Lists the shallowest heading level below the
    title and the level under it. Raises ValueError on marker damage or on a
    heading UNSLUGGABLE_RE matches."""
    lines, newline = _split(text)
    had_block = _block_span(lines) is not None
    body = _remove_block(lines)

    fm_end = _frontmatter_end(body)
    found = [(i + fm_end, level, t) for i, level, t in heading_lines(body[fm_end:])]
    slugs = anchors_for([(level, t) for _, level, t in found])
    title = next((k for k, (_, level, _) in enumerate(found) if level == 1), None)
    entries = [(level, t, slug) for k, ((_, level, t), slug) in enumerate(zip(found, slugs))
               if k != title and level > 1]
    if entries:
        top = min(level for level, _, _ in entries)
        entries = [e for e in entries if e[0] <= top + 1]
    has_quick_facts = any(t.strip().upper() == "QUICK FACTS" for _, _, t in found)
    long_enough = had_block or len("\n".join(body).splitlines()) > CONTENTS_THRESHOLD
    if has_quick_facts or len(entries) < 2 or not long_enough:
        return newline.join(body)
    bad = [t for _, t, _ in entries if UNSLUGGABLE_RE.search(re.sub(r"`[^`]*`", "", t))]
    if bad:
        raise ValueError(f"heading markup GitHub slugs differently: {bad[0]!r}")

    block = [CONTENTS_BEGIN, "**Contents**", ""]
    block += [f"{'  ' * (level - top)}- [{_link_text(t)}](#{slug})"
              for level, t, slug in entries]
    block += ["", CONTENTS_END]
    at = fm_end
    if title is not None and found[title][0] < fm_end + 40:
        at = found[title][0] + 1
    tail = body[at:]
    lead = [""] if at > 0 else []
    trail = [""] if tail and tail[0] != "" else []
    return newline.join(body[:at] + lead + block + trail + tail)


def contents_problems() -> list[str]:
    problems = []
    for path in contents_files():
        text = path.read_text(encoding="utf-8")
        try:
            fixed = with_contents(text)
        except ValueError as e:
            problems.append(f"{path.relative_to(ROOT)}: {e}")
            continue
        if fixed != text:
            problems.append(f"{path.relative_to(ROOT)}: CONTENTS block missing or stale "
                            "— rerun: python3 scripts/build_index.py")
    return problems


def write_contents() -> list[Path]:
    """Insert or refresh every owed CONTENTS block; return the files written."""
    written = []
    for path in contents_files():
        text = path.read_text(encoding="utf-8")
        fixed = with_contents(text)
        if fixed != text:
            path.write_text(fixed, encoding="utf-8")
            written.append(path)
    return written


def quick_facts_problems(path: Path) -> list[str]:
    """Contract violations for one SKILL.md (empty list = clean)."""
    text = path.read_text(encoding="utf-8")
    rel = path.relative_to(ROOT)
    heads = headings(text)
    try:
        line_count = len(without_contents(text).splitlines())
    except ValueError:  # marker damage: contents_problems() reports it
        line_count = len(text.splitlines())
    has_block = any(t.strip().upper() == "QUICK FACTS" for _, t in heads)

    problems = []
    if path.parent != ROOT and line_count > QUICK_FACTS_THRESHOLD and not has_block:
        problems.append(f"{rel}: {line_count} lines but no '## QUICK FACTS' block")
    if not has_block:
        return problems

    # Slice the QUICK FACTS section: from its heading to the next same-or-
    # higher-level heading.
    lines = text.splitlines()
    start = end = None
    for i, h_level, h_text in heading_lines(lines):
        if start is None and h_text.strip().upper() == "QUICK FACTS":
            start = i
            level = h_level
        elif start is not None and h_level <= level:
            end = i
            break
    block = "\n".join(lines[start:end])

    valid_anchors = set(anchors_for(heads))
    for link in re.findall(r"\]\(#([^)]+)\)", block):
        if link not in valid_anchors:
            problems.append(f"{rel}: QUICK FACTS anchor '#{link}' matches no heading")
    if not re.search(r"\]\(#", block):
        problems.append(f"{rel}: QUICK FACTS block has no anchor links into the body")
    return problems


def build_index_text() -> str:
    lines = [
        "# Heading Index (generated)",
        "",
        "<!-- GENERATED by scripts/build_index.py — DO NOT HAND-EDIT. -->",
        "<!-- Regenerate: python3 scripts/build_index.py   Verify: python3 scripts/build_index.py --check -->",
        "",
        "Anchor index of every `SKILL.md` heading, so grep-routing lands on",
        "anchors instead of archaeology. Link format: `path#anchor`.",
        "",
    ]
    for path in skill_files():
        rel = path.relative_to(ROOT).as_posix()
        lines.append(f"## {rel}")
        lines.append("")
        heads = headings(path.read_text(encoding="utf-8"))
        slugs = anchors_for(heads)
        for (level, text), slug in zip(heads, slugs):
            if level > INDEX_MAX_LEVEL:
                continue
            indent = "  " * (level - 1)
            lines.append(f"{indent}- [{text}]({rel}#{slug})")
        lines.append("")
    return "\n".join(lines) + "\n"


def run_checks() -> list[str]:
    problems = []
    for path in skill_files():
        problems.extend(quick_facts_problems(path))
    return problems + contents_problems()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[2])
    parser.add_argument("--check", action="store_true",
                        help="verify INDEX.md + QUICK FACTS contract; write nothing")
    args = parser.parse_args()

    if not args.check:
        for path in write_contents():
            print(f"wrote CONTENTS block: {path.relative_to(ROOT)}")
    problems = run_checks()
    text = build_index_text()

    if args.check:
        if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != text:
            problems.append("INDEX.md stale — rerun: python3 scripts/build_index.py")
        for p in problems:
            print(f"FAIL: {p}", file=sys.stderr)
        if not problems:
            print(f"INDEX.md in sync; QUICK FACTS + CONTENTS contracts hold "
                  f"({len(skill_files())} SKILL.md files, "
                  f"{len(contents_files())} files scanned for CONTENTS)")
        return 1 if problems else 0

    for p in problems:
        print(f"FAIL: {p}", file=sys.stderr)
    if problems:
        return 1
    INDEX.write_text(text, encoding="utf-8")
    print(f"wrote INDEX.md ({len(skill_files())} SKILL.md files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
